export function findGuideByPath(pathname: string): PageGuide {
  const clean = pathname === '/' ? '/' : pathname.replace(/\/+$/, '');
  const exact = PAGE_GUIDES.find((g) => g.path === clean);
  if (exact) return exact;
  return PAGE_GUIDES[0];
}
